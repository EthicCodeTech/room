#!/usr/bin/env python3
"""Generates Sources/RoomCore/SparkTraceData.swift from the Cinnabar spec so the logo and loader never drift.
Usage: scripts/gen_spark_paths.py [path/to/cinnabar-design-system.md]"""
import re, sys, os
spec = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Projects/cinnabar/cinnabar-design-system.md")
text = open(spec, encoding="utf-8").read()
start = text.index("### 8.3 The official loader")
block = text[start:text.index("### 8.4", start)]
logo = re.search(r'<path fill="#F7F7F5" fill-rule="evenodd" d="([^"]+)"', block).group(1)
motion = re.search(r'path="(M0 0[^"]+)"', block).group(1)
vb = re.search(r'viewBox="0 0 (\d+) (\d+)"', block).groups()
tr = re.search(r'translate\(([\d.]+) ([\d.]+)\)', block).groups()
r = re.search(r'<circle r="(\d+)"', block).group(1)
out = f'''// GENERATED by scripts/gen_spark_paths.py from cinnabar-design-system.md section 8.3. Do not edit.
import Foundation

/// The "ec" mark and the official Spark Trace loader path, verbatim from the Cinnabar spec.
public enum SparkTraceData {{
    public static let viewBoxWidth = {vb[0]}.0
    public static let viewBoxHeight = {vb[1]}.0
    /// Where the sindoor dot rests (the tip of the c).
    public static let restX = {tr[0]}
    public static let restY = {tr[1]}
    public static let dotRadius = {r}.0
    /// Outline of the joined "ec" (SVG path, even-odd fill).
    public static let logoPath = "{logo}"
    /// The dot's orbit, relative to the resting point (SVG path, constant speed).
    public static let motionPath = "{motion}"
}}
'''
dest = os.path.join(os.path.dirname(__file__), "..", "Sources", "RoomCore", "SparkTraceData.swift")
open(dest, "w").write(out)
print("wrote", os.path.normpath(dest), len(out), "bytes; logo", len(logo), "motion", len(motion))
